export const COUNTRY_CODES = Object.keys(COUNTRIES) as CountryCode[];

export function getCountry(code: string): CountryDef | undefined {
  return COUNTRIES[code.toUpperCase() as CountryCode];
}

/** Every locale registered for a country, in priority order. */
export function localesForCountry(code: string): string[] {
  return getCountry(code)?.locales ?? [];
}
